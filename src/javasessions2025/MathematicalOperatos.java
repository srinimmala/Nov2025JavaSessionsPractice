package javasessions2025;

public class MathematicalOperatos {

	public static void main(String[] args) {
		
		System.out.println(10+20);
		System.out.println(10-20);
		System.out.println(10*20);
		System.out.println(20/10);
		
		System.out.println(9/2);//4
		System.out.println(8/2);//4
		System.out.println(9.0/2);//4.5
		System.out.println(9/2.0);//4.5
		System.out.println(9.0/2.0);//4.5
		
		System.out.println(0/9);
		//System.out.println(9/0);//ArithmeticException: / by zero
		
		System.out.println(9.0 / 0);//Infinity
		System.out.println(9/0.0);//Infinity
		System.out.println(9.0 / 0.0); //Infinity
		
		//System.out.println(0/0);//AE
		
		System.out.println(0/0.0);//NaN - not a number
		System.out.println(0.0 / 0 );//NaN
		System.out.println(0.0/0.0);//NaN
		
		//System.out.println(100 / 0);//AE
		
		System.out.println(9.99 / 0);//Infinity
		
		
		// %
		System.out.println(9 % 2);//1
		System.out.println(8 % 2);//0
		System.out.println(20 % 3);//2
		System.out.println(100 % 5);//0
		System.out.println(100 % 7);//2
		
		
		

	}

}
